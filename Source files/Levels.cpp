// =====================================================
// LEVEL
// =====================================================

int currentLevel = 1;


// =====================================================
// LOAD LEVEL
// =====================================================

void loadLevel(int level)
{
    if (level < 1)
        level = 1;

    if (level > TOTAL_LEVELS)
        level = TOTAL_LEVELS;


    currentLevel = level;


    // Each level has its own 4-question group.
    currentQuestion =
        (currentLevel - 1) * 4;


    // Copy selected maze into active maze.
    for (int r = 0; r < Rows; r++)
    {
        for (int c = 0; c < Columns; c++)
        {
            maze[r][c] =
                LEVEL_MAZES[
                    currentLevel - 1
                ][r][c];
        }
    }


    // =================================================
    // RESET PACMAN
    // =================================================

    pacmanRow = 6;
    pacmanCol = 6;

    pacmanX =
        pacmanCol * CellSize;

    pacmanY =
        pacmanRow * CellSize;


    // =================================================
    // RESET GHOSTS
    // =================================================

    ghostRow = 8;
    ghostCol = 8;

    ghost2Row = 8;
    ghost2Col = 11;

    ghost3Row = 9;
    ghost3Col = 9;

    prevGhost3Row = -1;
    prevGhost3Col = -1;


    ghostX =
        ghostCol * CellSize;

    ghostY =
        ghostRow * CellSize;

    ghost2X =
        ghost2Col * CellSize;

    ghost2Y =
        ghost2Row * CellSize;

    ghost3X =
        ghost3Col * CellSize;

    ghost3Y =
        ghost3Row * CellSize;


    // =================================================
    // RESET DIRECTION
    // =================================================

    dirRow = 0;
    dirCol = 0;

    nextDirRow = 0;
    nextDirCol = 0;


    // =================================================
    // RESET QUIZ
    // =================================================

    quizActive = false;
    powerMode = false;
    showFeedback = false;


    // =================================================
    // RESET GHOST RETURN
    // =================================================

    ghost1Returning = false;
    ghost2Returning = false;
    ghost3Returning = false;


    // =================================================
    // RESET GAME OVER / WIN
    // =================================================

    isGameOver = false;
    isGameWon = false;


    // =================================================
    // PACMAN START CELL
    // =================================================

    maze[pacmanRow][pacmanCol] = 2;


    // =================================================
    // REBUILD GRAPH
    // =================================================

    buildGraph();


    // =================================================
    // RESET DFS
    // =================================================

    startDFS(
        ghost2Row,
        ghost2Col
    );


    // =================================================
    // RESET CLOCKS
    // =================================================

    pacmanClock.restart();
    ghostClock.restart();
    ghost2Clock.restart();
    ghost3Clock.restart();
}


// =====================================================
// LOAD NEXT LEVEL
// =====================================================

void loadNextLevel()
{
    if (currentLevel < TOTAL_LEVELS)
    {
        loadLevel(
            currentLevel + 1
        );
    }
    else
    {
        isGameWon = true;
    }
}
